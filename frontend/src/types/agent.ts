/**
 * Agent-related TypeScript types.
 * Mirror of backend/app/models/agent.py — keep both files in sync.
 */

// ---------------------------------------------------------------------------
// Primitives
// ---------------------------------------------------------------------------

export type AgentRole =
  | "Researcher"
  | "Analyst"
  | "Processor"
  | "Validator"
  | "Summarizer"
  | "General Worker";

export type AgentStatus = "idle" | "running" | "waiting" | "failed" | "completed";

/**
 * Distinguishes agents that exist from simulation start (conventional manager
 * uses only these) from agents that are dynamically activated by POSDCORB.
 */
export type AgentOrigin = "initial" | "dynamic";

/** A single declared capability, e.g. "search", "python", "stats". */
export type Capability = string;

// ---------------------------------------------------------------------------
// Core agent model — every field maps to a backend column / Pydantic field
// ---------------------------------------------------------------------------

export interface Agent {
  /** Stable identifier, e.g. "agt-001". Generated by backend. */
  id: string;

  /** Human-readable label. */
  name: string;

  /** Functional role within the MAS. */
  role: AgentRole;

  /**
   * Declared capabilities / skills.
   * The task scheduler uses these to route tasks to capable agents.
   */
  capabilities: Capability[];

  /**
   * Normalised processing speed multiplier.
   * 1.0 = baseline; 0.5 = half speed; 2.0 = double speed.
   * Range: 0.1 – 5.0
   */
  processing_speed: number;

  /**
   * Probability (0–1) that the agent completes a task successfully.
   * At simulation time this is sampled per task execution.
   */
  reliability: number;

  /**
   * Maximum number of tasks this agent can process concurrently.
   * Range: 1–16
   */
  max_concurrent_tasks: number;

  // -- Runtime state (populated/updated by the simulation engine) -----------

  /** Current number of active tasks. Reset to 0 before each simulation run. */
  current_workload: number;

  /** Agent's current lifecycle state. */
  status: AgentStatus;

  /** Simulated CPU utilisation percentage (0–100). */
  cpu_usage: number;

  /** Cumulative tasks completed across all runs tracked in this pool entry. */
  tasks_completed: number;

  /** Cumulative tasks failed. */
  tasks_failed: number;

  // -- Pool metadata ---------------------------------------------------------

  /**
   * Whether this agent is part of the fixed initial pool or was dynamically
   * activated (POSDCORB only).
   *
   * - "initial"  → available to BOTH managers from t=0.
   * - "dynamic"  → reserved for POSDCORB; ignored by Conventional Manager.
   */
  origin: AgentOrigin;

  /** ISO-8601 creation timestamp. */
  created_at: string;
}

// ---------------------------------------------------------------------------
// API shapes
// ---------------------------------------------------------------------------

/** Payload for POST /api/agents */
export interface CreateAgentRequest {
  name: string;
  role: AgentRole;
  capabilities: Capability[];
  processing_speed: number;
  reliability: number;
  max_concurrent_tasks: number;
  origin: AgentOrigin;
}

/** Payload for PATCH /api/agents/:id */
export type UpdateAgentRequest = Partial<CreateAgentRequest>;

export interface AgentResponse {
  agent: Agent;
  message: string;
}

export interface AgentListResponse {
  agents: Agent[];
  total: number;
  initial_count: number;
  dynamic_count: number;
}
